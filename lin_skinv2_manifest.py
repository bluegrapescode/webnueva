_cache = None


def data():
    """The sidecar bytes, or ``None``.  Never raises.

    Verified against :data:`SHA256` every time it is decoded, so a corrupted
    blob is an absent manifest (a named state) rather than a malformed table
    the contract would have to reject downstream.
    """
    global _cache
    if _cache is not None:
        return _cache or None
    try:
        raw = zlib.decompress(base64.b64decode(_BLOB))
    except Exception:
        _cache = b""
        return None
    if len(raw) != SIZE or hashlib.sha256(raw).hexdigest() != SHA256:
        _cache = b""
        return None
    _cache = raw
    return raw


def _already_correct(path):
    try:
        if path.stat().st_size != SIZE:
            return False
        return hashlib.sha256(path.read_bytes()).hexdigest() == SHA256
    except OSError:
        return False


def install(*candidate_dirs):
    """Materialise the sidecar into the first candidate that accepts it.

    Returns the :class:`~pathlib.Path` of a file that is proven correct on
    disk, or ``None`` when every candidate failed.  ★ NEVER RAISES - the caller
    is an import at web-app boot, and an owner whose disk is read-only must get
    the contract's named ``no_manifest`` state, not a site that will not start.

    Idempotent: an existing file with the right size and digest is left exactly
    as it is, so a restart costs no I/O and no mtime churn.  The write itself
    goes to a ``.part`` sibling and is moved in with :func:`os.replace`, so a
    crash mid-write can never leave a torn table where a good one was.
    """
    raw = data()
    if raw is None:
        return None
    for candidate in candidate_dirs:
        if not candidate:
            continue
        try:
            directory = Path(candidate)
            target = directory / LEAF
            if _already_correct(target):
                return target
            directory.mkdir(parents=True, exist_ok=True)
            part = directory / (LEAF + ".part.%d" % os.getpid())
            try:
                part.write_bytes(raw)
                os.replace(str(part), str(target))
            finally:
                try:
                    part.unlink()
                except OSError:
                    pass
            if _already_correct(target):
                return target
        except Exception:
            continue
    return None
